"""
auto_amk - generated by projects.get_project(). Adjust setup()/main()/
end_run() and config/ to fit what this project actually needs to do.
This template runs a Tello with a livelogger controlled by keyboard and
flies an orbit (circle with the nose pointed at the center).
"""

import asyncio
import math

from core.controller import ControllerType, get_controller
from core.drone import DroneType, get_drone
from core.logger import LoggerType, LogLevel, get_logger
from core.video import VideoOutputType, get_videostream
from projects.base import ProjectBase

qwertz_startup = """
QWERTZ KEYBOARD CONTROLS

# Util
C           = connect
V/B         = arm / disarm
Z/U         = get position / attitude
I/O         = start/stop state receiver

# Movement Util
T/L         = takeoff / land
Space       = emergency

# Movement
W/S         = up / down
A/D         = left / right yaw
Up/Down     = forward / backward
Left/Right  = left / right move
"""

# ---- Orbit parameters ----
RADIUS_CM = 100  # circle radius. The center must be this far straight AHEAD of the nose.
SPEED_CMS = 20  # tangential speed (cm/s) - start slow
LAPS = 1
CLOCKWISE = True  # as seen from above

# ---- Calibration (tune on your drone) ----
# Real speed per 1 Tello RC unit (the -100..100 scale). Measure it: hold
# rc x=0.3 (30 units) for 2 s, measure the distance, divide by 2 s and by 30.
CMS_PER_RC = 1.0  # (cm/s) per RC unit, lateral
DEG_PER_S_PER_RC = 0.7  # (deg/s) per RC unit, yaw

RATE_HZ = 10  # rc send rate during the orbit. Each rc() call also publishes an ACK on the bus.

# The Tello lands by itself if it gets NO command for 15 s. While we wait
# (after takeoff, after the orbit) we send "rc 0 0 0 0" this often as a keepalive.
HOVER_KEEPALIVE_S = 1.0


class auto_amk(ProjectBase):
    async def setup(self) -> None:
        self.live_logger = get_logger(LoggerType.LIVE_CONSOLE, min_level=LogLevel.INFO)

        self.recorder.attach(self.bus)
        self.bus.subscribe("*", self.live_logger.log_bus_event)

        d1_conf = self.drone_config["drone_1"]
        drone_type = DroneType[d1_conf["drone_type"].upper()]
        self.drone1 = get_drone(drone_type, d1_conf["drone_id"], bus=self.bus, ip=d1_conf["ip"])

        self.video1 = get_videostream(VideoOutputType.CV2, drone_id=d1_conf["drone_id"], bus=self.bus, media_dir=self.log_dir / "media")

        layout = self.app_config.get("controller", {}).get("layout") or None
        self.controller = get_controller(ControllerType.KEYBOARD, drone_id=d1_conf["drone_id"], bus=self.bus, layout=layout)

    async def main(self) -> None:
        await self.controller.start_controller()
        print(qwertz_startup)

        await self.drone1.connect()  # c
        await self.drone1.set(what="arm")  # v
        await self.drone1.start_state_receiver()  # i

        await self.drone1.start_video()
        await self.video1.start_stream()
        await self.video1.turn_on_display_state_data()
        await self.video1.start_detection()

        # await self.drone1.takeoff()

        # # NOT asyncio.sleep(): idle for >15 s makes the Tello auto-land.
        # await self.hover(8)

        # await self.orbit()

        if self._in_air():
            await self.hover(3)
            await self.drone1.land()

        await asyncio.Event().wait()

    async def end_run(self) -> None:
        if self.drone1.video_streaming:
            await self.drone1.stop_video()
        if self.drone1.flight_state.value == "inair":
            await self.drone1.land()
        if self.drone1.con_state.value == "connected":
            await self.drone1.disconnect()
        if self.video1.is_object_detecting:
            await self.video1.stop_detection()
        if self.video1.is_running:
            await self.video1.stop_stream()
            await self.video1.stop_recording()
        await self.controller.stop_controller()
        self.recorder.detach(self.bus)
        self.drone1.detach()

    def _in_air(self) -> bool:
        return self.drone1.flight_state.value == "inair"

    async def hover(self, seconds: float) -> None:
        """Hold position for `seconds` while sending rc 0 0 0 0 every
        HOVER_KEEPALIVE_S, so the Tello's 15 s no-command auto-land never triggers."""
        loop = asyncio.get_running_loop()
        t_end = loop.time() + seconds
        while loop.time() < t_end and self._in_air():
            await self.drone1.rc(0, 0, 0, 0)
            await asyncio.sleep(min(HOVER_KEEPALIVE_S, max(0.0, t_end - loop.time())))

    async def orbit(self) -> None:
        """Circle around a point RADIUS_CM straight ahead of the nose,
        keeping the nose pointed at the center.

        Tello rc order (SDK): a = left/right, b = forward/back, c = up/down,
        d = yaw (positive = clockwise). TelloDrone.rc(x, y, z, yaw) maps
        1:1 onto a, b, c, d and expects values in -1.0..1.0 (it multiplies by 100).
        """
        await self.video1.start_recording()
        # Tangential speed -> lateral RC units (-100..100); omega = v / r -> yaw RC units.
        lr_units = SPEED_CMS / CMS_PER_RC
        yaw_units = math.degrees(SPEED_CMS / RADIUS_CM) / DEG_PER_S_PER_RC
        lr_units = max(-100.0, min(100.0, lr_units))
        yaw_units = max(-100.0, min(100.0, yaw_units))

        # Facing center + strafe right = counter-clockwise (top view), nose turns left.
        if CLOCKWISE:
            lr_units, yaw_units = -lr_units, +yaw_units
        else:
            lr_units, yaw_units = +lr_units, -yaw_units

        # drone.rc() wants -1..1, so normalize here.
        lr = lr_units / 100.0
        yaw = yaw_units / 100.0

        duration = LAPS * 2 * math.pi * RADIUS_CM / SPEED_CMS
        period = 1.0 / RATE_HZ
        print(f"orbit: lr={lr_units:.0f} yaw={yaw_units:.0f} (rc units), {duration:.1f}s")

        loop = asyncio.get_running_loop()
        t_end = loop.time() + duration
        next_tick = loop.time()

        try:
            while loop.time() < t_end:
                # Stop if the drone is no longer flying (emergency key, landed, etc.)
                if not self._in_air():
                    print("orbit: drone not in air anymore, aborting")
                    return
                await self.drone1.rc(lr, 0, 0, yaw)
                # fixed-rate loop so timing doesn't drift with the rc() overhead
                next_tick += period
                await asyncio.sleep(max(0.0, next_tick - loop.time()))
        finally:
            # always stop and hover, even if cancelled - but only if still flying
            if self._in_air():
                await self.drone1.rc(0, 0, 0, 0)
            await self.video1.stop_recording()

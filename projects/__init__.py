"""
public API of core.projects (well, projects - top-level, not under core).

    from projects import get_project

get_project(name) returns an existing project if one is already on
disk at <root>/<name>/, or scaffolds a brand-new one with the same
folder layout every hand-built example uses (commander/, config/,
logs/) and returns that instead.
"""

import importlib.util
import sys
from pathlib import Path
from sys import modules

from core.fileops import get_fileops

from .base import ProjectBase

PATH_ROOT = Path(__file__).resolve().parent

_APP_CONFIG_TEMPLATE = """\
[logging]
level = "INFO"

[controller]
layout = "keyboard"   # keyboard | keyboard_video | t8l_pos | t8l_video
"""

_DRONE_CONFIG_TEMPLATE = """\
{
  "drone_1": {
    "drone_type": "sim_simdrone",
    "drone_id": "drone1",
    "ip": "67.67.0.1",
    "port": "6767"
  }
}
"""

_MAIN_TEMPLATE = '''"""
# {name} - generated by projects.get_project()
Runs the simdrone with the keyboard. Adjust setup()/main()/end_run() and config/
to what this project needs - projects/examples/ shows video, T8L, ArUco, YOLO, Vicon, ...

## Run
    python run.py run -n {name}
"""

import asyncio

from core.controller import ControllerType, get_controller
from core.logger import LoggerType, get_logger
from projects.base import ProjectBase


class {name}(ProjectBase):
    async def setup(self) -> None:
        # every bus message -> console, and recorded to logs/bus_logs/
        self.live_logger = get_logger(LoggerType.LIVE_CONSOLE, min_level=self.log_level)
        self.recorder.attach(self.bus)
        self.bus.subscribe("*", self.live_logger.log_bus_event)

        # drone from config/mydrone.json
        self.drone1 = self.create_drone("drone_1")

        # controller, layout from config/defaults.toml
        layout = self.app_config.get("controller", {{}}).get("layout")
        self.controller = get_controller(ControllerType.KEYBOARD, drone_id=self.drone1.drone_id, bus=self.bus, layout=layout)

    async def main(self) -> None:
        await self.controller.start_controller()
        print(self.controller.controls_text())
        await asyncio.Event().wait()  # runs until CTRL+C, then end_run()

    async def end_run(self) -> None:
        await self.shutdown_drone(self.drone1)
        await self.controller.stop_controller()
        self.recorder.detach(self.bus)
'''


def _scaffold_project_files(project_dir: Path, name: str) -> None:
    """Create the standard folder structure and starter files for a
    project, matching the layout every hand-built example already
    uses. Never overwrites a file that's already there."""
    fops = get_fileops()

    fops.ensure_dir(project_dir / "commander")
    (project_dir / "commander" / "__init__.py").touch(exist_ok=True)
    main_path = project_dir / "commander" / "main.py"
    if not main_path.exists():
        main_path.write_text(_MAIN_TEMPLATE.format(name=name), encoding="utf-8")

    config_dir = fops.ensure_dir(project_dir / "config")
    defaults_path = config_dir / "defaults.toml"
    if not defaults_path.exists():
        defaults_path.write_text(_APP_CONFIG_TEMPLATE, encoding="utf-8")

    drone_path = config_dir / "mydrone.json"
    if not drone_path.exists():
        drone_path.write_text(_DRONE_CONFIG_TEMPLATE, encoding="utf-8")

    for sub in ("bus_logs", "media"):
        fops.ensure_dir(project_dir / "logs" / sub)


_HELPER_DIRS: set[str] = set()


def _forget_other_helpers(keep: str) -> None:
    """Another project loaded before in this process: drop its commander/ from sys.path and
    its helper modules from the import cache, so a same-named helper (control.py) of THIS
    project is imported instead of the old one."""
    for folder in list(_HELPER_DIRS - {keep}):
        if folder in sys.path:
            sys.path.remove(folder)
        for mod_name, mod in list(modules.items()):
            file = getattr(mod, "__file__", None) or ""
            if file and str(Path(file).resolve().parent) == folder:
                del modules[mod_name]
        _HELPER_DIRS.discard(folder)


def _load_project_class(project_dir: Path, name: str):
    """Import commander/main.py directly from disk and return its
    `name` class. Uses importlib.util.spec_from_file_location instead
    of a dotted module path (e.g. "projects.examples.foo.commander.main")
    so this works regardless of how/whether `projects` happens to be on
    sys.path - it only needs the file's location, nothing else."""
    main_path = project_dir / "commander" / "main.py"
    # helper files next to main.py (e.g. commander/pose.py) can be imported by name: `from pose import ...`
    commander_dir = str(main_path.parent.resolve())
    _forget_other_helpers(commander_dir)
    if commander_dir not in sys.path:
        sys.path.insert(0, commander_dir)
    _HELPER_DIRS.add(commander_dir)
    spec = importlib.util.spec_from_file_location(f"_project_{name}", main_path)
    module = importlib.util.module_from_spec(spec)
    modules[spec.name] = module
    spec.loader.exec_module(module)
    if hasattr(module, name):
        return getattr(module, name)
    # class named differently from the folder: take the one ProjectBase subclass defined in main.py
    found = [obj for obj in vars(module).values() if isinstance(obj, type) and issubclass(obj, ProjectBase) and obj is not ProjectBase]
    if len(found) == 1:
        return found[0]
    raise AttributeError(f"{main_path} must define a ProjectBase subclass named '{name}' (the folder name)")


def get_project(
    name: str = "new_project",
    path: Path = PATH_ROOT,
    **kwargs,
) -> ProjectBase:
    """Get a project if it already exists on disk, otherwise scaffold a
    brand-new one (folder structure + starter templates) and return it."""
    project_dir = Path(path).resolve() / name

    _scaffold_project_files(project_dir, name)
    project_cls = _load_project_class(project_dir, name)
    return project_cls(project_dir, **kwargs)


__all__ = ["ProjectBase", "get_project"]
